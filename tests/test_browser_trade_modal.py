"""Browser smoke test for the commodity trade modal (I66).

This is the first test in the repo that renders the UI in a real
browser — every earlier batch exercised the web only through
TestClient, which never runs the JavaScript. The setup is:
- a fixture entity (real config.yaml + journals under tmp_path),
- the FastAPI app served by uvicorn in a thread *in this process*,
  so the monkeypatched entity resolution applies to the server too
  (a subprocess server would read the repo's real global.yaml),
- Playwright driving headless Chromium against it.

Skips cleanly when Playwright, uvicorn, or a launchable Chromium is
absent (pytest.importorskip + a launch probe), following the repo's
existing skip pattern for a missing hledger. Setup, not the test:
`pip install playwright && python -m playwright install chromium`
in the repo venv (both already done on this VM).

What it proves: the Commodities tab renders in a real browser, the
Buy modal opens with its fields, submitting a buy records it (the
generated investments journal gains the entry), and the Sell modal
shows the live holding preview from the books before recording a
sale. It does not need pricehist or yfinance: the trade modal reads
holdings from the journal, not from a price fetch.

One shim, and why it is honest: index.html loads Chart.js from the
jsdelivr CDN, and the page's top-level `Chart.defaults.*` statements
abort the whole script when Chart is undefined — so in an environment
where the CDN is unreachable, no page JavaScript runs at all (the
launcher, init, and the trade modal are all defined after those
lines). This VM's browser cannot reach the CDN (proxy tunnel
failure), even though curl can. The test therefore fulfils the three
CDN script requests from byte-identical vendored copies under
tests/fixtures/chartjs/ (exact versions from index.html). The shim
restores the page to the state a normal browser reaches; it does not
touch the modal or the endpoints under test.
"""

