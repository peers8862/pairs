CONFIG_YAML = """pair:
  currency: CAD
accounts:
  bank: Assets:Current:Chequing
  capital_gains: Income:Non-Operating:Capital Gains
  registered_gains: Income:Non-Operating:Registered Gains
market:
  commodities:
    - symbol: TSLA
      name: Tesla
      source: yahoo
      fetch_pair: TSLA
      currency: CAD
      tax_account: taxable
"""

PRICES = """P 2026-11-10 TSLA CAD 480.00
P 2026-11-12 TSLA CAD 510.25
"""

GLOBAL = {"active": "fixture",
          "entities": [{"slug": "fixture", "name": "Fixture",
                        "currency": "CAD"}]}


def _free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


@pytest.fixture()
def browser_env(tmp_path, monkeypatch):
    """Fixture entity + in-process server. Yields (base_url, entity_dir)."""
    entity_dir = tmp_path / "entity"
    include = entity_dir / "include"
    include.mkdir(parents=True)
    (entity_dir / "config.yaml").write_text(CONFIG_YAML)
    (include / "prices.journal").write_text(PRICES)

    # A prior buy of 10 TSLA, generated by the real builder so the
    # fixture journal is exactly what the CLI writes.
    buy = inv.build_buy_entry(
        date="2026-07-20", symbol="TSLA", qty=10, unit_price=500.0,
        quote_currency="CAD", fx=1.0, fee=0.0, tax_account="taxable",
        cash_account="Assets:Current:Chequing", entity_currency="CAD")
    (include / "entity.journal").write_text(
        "2026-01-02 * Opening balance\n"
        "    Assets:Current:Chequing    CAD 100000.00\n"
        "    Equity:Opening             CAD -100000.00\n\n" + buy)

    # Point every entity-resolution path at the fixture. The server
    # runs in this process, so these patches apply to it as well.
    monkeypatch.setattr(helpers, "get_entity_dir", lambda: entity_dir)
    monkeypatch.setattr(helpers, "load_global_config", lambda: dict(GLOBAL))
    monkeypatch.setattr(ui, "get_entity_dir", lambda: entity_dir)
    monkeypatch.setattr(ui, "load_global_config", lambda: dict(GLOBAL))
    monkeypatch.setattr(web, "get_entity_dir", lambda: entity_dir)
    monkeypatch.setattr(market, "get_entity_dir", lambda: entity_dir)

    app = web.create_app()
    port = _free_port()
    server = uvicorn.Server(uvicorn.Config(
        app, host="127.0.0.1", port=port, log_level="warning"))
    thread = threading.Thread(target=server.run, daemon=True)
    thread.start()
    base_url = f"http://127.0.0.1:{port}"
    deadline = time.time() + 30
    while True:
        try:
            with urllib.request.urlopen(base_url + "/api/status",
                                        timeout=2) as r:
                assert r.status == 200
            break
        except Exception:
            if time.time() > deadline:
                server.should_exit = True
                raise RuntimeError("test server did not start")
            time.sleep(0.2)
    yield base_url, entity_dir
    server.should_exit = True
    thread.join(timeout=10)


def _open_commodities(page, base_url):
    """Load the app and open the Commodities tab; return the TSLA row."""
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    # CDN shim: fulfil the three Chart.js requests from vendored copies
    # (see module docstring) so the page's script runs to completion.
    fixtures = Path(__file__).resolve().parent / "fixtures" / "chartjs"
    for url, name in {
        "https://cdn.jsdelivr.net/npm/chart.js@4.4.4/dist/chart.umd.min.js":
            "chart.umd.min.js",
        "https://cdn.jsdelivr.net/npm/chartjs-chart-sankey@0.14.0/dist/chartjs-chart-sankey.min.js":
            "chartjs-chart-sankey.min.js",
        "https://cdn.jsdelivr.net/npm/chartjs-chart-treemap@3.1.0/dist/chartjs-chart-treemap.min.js":
            "chartjs-chart-treemap.min.js",
    }.items():
        path = str(fixtures / name)
        # This Playwright version calls the handler as handler(route, request).
        page.route(url, lambda route, _request, p=path: route.fulfill(
            path=p, content_type="application/javascript"))
    page.goto(base_url, wait_until="domcontentloaded")
    page.locator("#brand-icon").click()
    page.locator('.launcher-icon[title="Commodities"]').click()
    row = page.locator(".commodity-row", has_text="TSLA")
    row.wait_for(state="visible", timeout=15000)
    return row, errors


def test_buy_modal_renders_and_records_buy(browser_env):
    base_url, entity_dir = browser_env
    with sync_playwright() as p:
        try:
            browser = p.chromium.launch()
        except Exception as e:
            pytest.skip(f"Chromium did not launch: {e}")
        page = browser.new_page()
        row, errors = _open_commodities(page, base_url)

        row.locator("button", has_text="Buy").click()
        modal = page.locator("#trade-modal")
        modal.wait_for(state="visible", timeout=10000)
        assert page.locator("#trade-modal-title").inner_text() == "Buy TSLA"
        for field in ("#td-qty", "#td-price", "#td-fee", "#td-date",
                      "#td-submit"):
            assert page.locator(field).is_visible(), f"{field} not visible"

        page.fill("#td-qty", "5")
        page.fill("#td-price", "100")
        page.fill("#td-fee", "0")
        page.locator("#td-submit").click()
        modal.wait_for(state="hidden", timeout=10000)
        # Toast confirms the recorded buy.
        page.locator(".toast", has_text="Bought 5 TSLA").wait_for(timeout=10000)

        written = entity_dir / "generated" / "2026" / "investments.journal"
        assert written.exists()
        assert "TSLA" in written.read_text()
        assert "5 TSLA" in written.read_text()
        assert not errors, f"page errors: {errors}"
        browser.close()


def test_sell_modal_shows_holding_and_records_sell(browser_env):
    base_url, entity_dir = browser_env
    with sync_playwright() as p:
        try:
            browser = p.chromium.launch()
        except Exception as e:
            pytest.skip(f"Chromium did not launch: {e}")
        page = browser.new_page()
        row, errors = _open_commodities(page, base_url)

        row.locator("button", has_text="Sell").click()
        modal = page.locator("#trade-modal")
        modal.wait_for(state="visible", timeout=10000)
        assert page.locator("#trade-modal-title").inner_text() == "Sell TSLA"
        # Live holding preview from the books: 10 held @ 500 average.
        preview = page.locator("#td-preview")
        preview.wait_for(state="visible", timeout=10000)
        page.wait_for_function(
            "document.getElementById('td-preview').textContent.includes('Held:')",
            timeout=10000)
        assert "Held: 10" in preview.inner_text()
        assert "500" in preview.inner_text()

        page.fill("#td-qty", "5")
        page.fill("#td-price", "600")
        page.fill("#td-fee", "0")
        page.locator("#td-submit").click()
        modal.wait_for(state="hidden", timeout=10000)
        page.locator(".toast", has_text="Sold 5 TSLA").wait_for(timeout=10000)

        written = entity_dir / "generated" / "2026" / "investments.journal"
        assert written.exists()
        assert "-5 TSLA" in written.read_text()
        assert not errors, f"page errors: {errors}"
        browser.close()
