from lib.helpers import (
    BASE_DIR, GLOBAL_CONFIG_FILE,
    load_global_config, save_global_config,
    prompt, validate_slug, ensure_dir, expand_path, slugify
)
from lib.journal import write_journal_atomic

import yaml


# ─── Directory structure for an entity ───────────────────────────────────────

ENTITY_DIRS = [
    'assets',
    'liabilities',
    'contacts',
    'contracts',
    'projects',
    'deferred',
    'recurring',
    'journal',
    'generated',
    'include',
    'invoices',
    'timesheets',
]


def cmd_init():
    """First-time setup for pair — multi-entity aware."""
    # If global.yaml already exists, tell user to use 'pair entity add'
    if GLOBAL_CONFIG_FILE.exists():
        print("Already initialized (global.yaml exists).")
        print("Use 'pair entity add' to add another entity.")
        return

    print("pair — business accounting on hledger\n")
    print("This tool supports multiple entities (Company/Project) and holding structures.")
    print("Let's set up your first entity.\n")

    # Entity identity
    entity_name = prompt("Entity name (Company/Project)")
    default_slug = slugify(entity_name)
    slug = prompt("Slug (short identifier)", default=default_slug, validator=validate_slug)
    currency = prompt("Default currency", default="CAD")
    journal_file = prompt("Main hledger journal file", default="~/.hledger.journal")

    # Primary bank account
    bank_name = prompt("Primary bank account name", default="Chequing")
    bank_account = f"Assets:Current:{bank_name}"

    # Fiscal year
    fiscal_start = prompt("Fiscal year start month (1-12)", default="1")

    # Create global.yaml
    global_config = {
        'active': slug,
        'entities': [
            {
                'name': entity_name,
                'slug': slug,
                'currency': currency,
                'journal_file': journal_file,
            }
        ]
    }
    save_global_config(global_config)
    print(f"\n  Created global.yaml")

    # Create entity directory structure
    entity_dir = BASE_DIR / 'entities' / slug
    for d in ENTITY_DIRS:
        ensure_dir(entity_dir / d)
    print(f"  Created entities/{slug}/ directory structure")

    # Create config.yaml
    config = {
        'pair': {
            'name': entity_name,
            'slug': slug,
            'currency': currency,
        },
        'journal_file': journal_file,
        'accounts': {
            'bank': bank_account,
            'receivable': 'Assets:Current:Accounts Receivable',
            'payable': 'Liabilities:Current:Accounts Payable',
        },
        'divisions': [],
        'defaults': {
            'fiscal_year_start': int(fiscal_start),
        }
    }
    config_path = entity_dir / 'config.yaml'
    with open(config_path, 'w') as f:
        yaml.dump(config, f, default_flow_style=False, sort_keys=False)
    print(f"  Created entities/{slug}/config.yaml")

    # Create accounts.journal
    accounts_path = entity_dir / 'include' / 'accounts.journal'
    write_journal_atomic(accounts_path, _default_accounts(bank_account, currency))
    print(f"  Created entities/{slug}/include/accounts.journal")

    # Create company.journal (aggregator — keeps filename for hledger compat)
    company_journal_path = entity_dir / 'include' / 'company.journal'
    aggregator_content = f"""; {entity_name} — master include file
; Generated by: pair init

include accounts.journal
"""
    write_journal_atomic(company_journal_path, aggregator_content)
    print(f"  Created entities/{slug}/include/company.journal")

    # Create or update the main journal file
    journal_path = expand_path(journal_file)
    include_line = f"include {entity_dir}/include/company.journal\n"

    if not journal_path.exists():
        journal_path.parent.mkdir(parents=True, exist_ok=True)
        with open(journal_path, 'w') as f:
            f.write(f"; {entity_name} — main ledger\n")
            f.write(f"; Created by: pair init\n\n")
            f.write(include_line)
        print(f"\n  Created {journal_file} with include line.")
    else:
        content = journal_path.read_text()
        if str(entity_dir / 'include' / 'company.journal') not in content:
            print(f"\n  Add this line to {journal_file}:")
            print(f"    {include_line.strip()}")
        else:
            print(f"\n  {journal_file} already includes company.journal.")

    # Summary
    print(f"\n  Active entity: {entity_name} ({slug})")
    print(f"  You're ready. Try 'pair asset add' or 'pair worth'.")


